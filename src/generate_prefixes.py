#!/usr/bin/env python3
"""Generate C++ header with SI prefixes from hepunits."""

import sys
from pathlib import Path

# Add the hepunits package to the path
sys.path.insert(0, '.pixi/envs/default/lib/python3.14/site-packages')

from hepunits.units.prefixes import *

# SI prefixes and their values
si_prefixes = {
    'quetta': quetta,
    'ronna': ronna,
    'yotta': yotta,
    'zetta': zetta,
    'exa': exa,
    'peta': peta,
    'tera': tera,
    'giga': giga,
    'mega': mega,
    'kilo': kilo,
    'hecto': hecto,
    'deca': deca,
    'deci': deci,
    'centi': centi,
    'milli': milli,
    'micro': micro,
    'nano': nano,
    'pico': pico,
    'femto': femto,
    'atto': atto,
    'zepto': zepto,
    'yocto': yocto,
    'ronto': ronto,
    'quecto': quecto,
}

# Binary prefixes
binary_prefixes = {
    'kibi': kibi,
    'mebi': mebi,
    'gibi': gibi,
    'tebi': tebi,
    'pebi': pebi,
    'exbi': exbi,
    'zebi': zebi,
    'yobi': yobi,
}

# Miscellaneous prefixes
misc_prefixes = {
    'googol': googol,
}

def generate_prefixes_header(output_path: Path) -> None:
    """Generate C++ header with SI prefixes."""
    
    with open(output_path, 'w') as f:
        f.write("// Generated C++ header with SI prefixes from hepunits\n")
        f.write("// DO NOT EDIT - This file is automatically generated\n")
        f.write("\n")
        f.write("#pragma once\n")
        f.write("\n")
        f.write("namespace physicalconstants {\n")
        f.write("\n")
        f.write("namespace prefixes {\n")
        f.write("\n")
        
        # Write SI prefixes
        f.write("    // SI prefixes\n")
        for name, value in sorted(si_prefixes.items()):
            f.write(f"    constexpr double {name} = {value:.1e};  // {name}\n")
        
        f.write("\n")
        
        # Write binary prefixes
        f.write("    // Binary prefixes\n")
        for name, value in sorted(binary_prefixes.items()):
            f.write(f"    constexpr double {name} = {value:.1e};  // {name}\n")
        
        f.write("\n")
        
        # Write miscellaneous prefixes
        f.write("    // Miscellaneous prefixes\n")
        for name, value in sorted(misc_prefixes.items()):
            f.write(f"    constexpr double {name} = {value:.1e};  // {name}\n")
        
        f.write("\n")
        f.write("} // namespace prefixes\n")
        f.write("\n")
        f.write("} // namespace physicalconstants\n")

if __name__ == '__main__':
    output_file = Path('output/prefixes.hpp')
    generate_prefixes_header(output_file)
    print(f"Generated {output_file}")